#!/usr/bin/env python3
"""Generate the freestanding ColdFire codec, following Euclid's C workflow."""
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
FLAGS = ['-mcpu=5475', '-msoft-float', '-O2', '-ffreestanding', '-fno-builtin',
         '-fno-common', '-fno-jump-tables', '-fno-asynchronous-unwind-tables',
         '-fno-ident', '-fomit-frame-pointer', '-Wall', '-Wextra', '-Werror']


def generate(unit="retention"):
    with tempfile.TemporaryDirectory() as td:
        asm = pathlib.Path(td) / 'retention.s'
        subprocess.run(['m68k-elf-gcc', *FLAGS, '-S',
                        f'modules/plocks-p2/{unit}.c', '-o', str(asm)], cwd=ROOT, check=True)
        source = asm.read_text()
        if '*8)' in source:
            raise RuntimeError('hardware-unsafe scaled-*8 ColdFire address mode')
        return f'| Generated by generate_retention.py; edit {unit}.c.\n' + source


if __name__ == '__main__':
    for unit in ('retention', 'pool'):
        source = generate(unit)
        dest = HERE / f'{unit}.s'
        if '--check' in sys.argv:
            if not dest.exists() or source != dest.read_text():
                sys.exit(f'PLOCKS P2 {unit}.s is stale: run generate_retention.py')
        else:
            dest.write_text(source)
    if '--check' in sys.argv:
        print('PLOCKS P2 ColdFire source matches C')
